class Command(BaseCommand):
    help = "한국 인기 대표 요리 레시피 20여 개를 데이터베이스에 일괄 추가합니다."

    def add_arguments(self, parser):
        parser.add_argument(
            "--clear",
            action="store_true",
            help="기존 레시피를 모두 삭제하고 새로 추가합니다."
        )

    def handle(self, *args, **options):
        User = get_user_model()
        admin_user, _ = User.objects.get_or_create(
            username="chef_admin",
            defaults={"is_staff": True, "is_superuser": True}
        )

        if options["clear"]:
            count = Recipe.objects.count()
            Recipe.objects.all().delete()
            self.stdout.write(self.style.WARNING(f"기존 레시피 {count}개를 삭제했습니다."))

        created_count = 0
        updated_count = 0

        for item in SAMPLE_RECIPES:
            obj, created = Recipe.objects.update_or_create(
                title=item["title"],
                defaults={
                    "author": admin_user,
                    "description": item["description"],
                    "ingredients": item["ingredients"],
                    "steps": item["steps"],
                }
            )
            if created:
                created_count += 1
            else:
                updated_count += 1

        self.stdout.write(
            self.style.SUCCESS(
                f"✅ 레시피 데이터베이스 시딩 완료! (신규 생성: {created_count}개, 업데이트: {updated_count}개, 총: {Recipe.objects.count()}개)"
            )
        )
